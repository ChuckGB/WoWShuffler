# Builds Data_NumMade.lua: recipes that make more than one item per cast.
# LibProfessionDB has no "number made" field, so this one fact comes from
# AtlasLootClassic's profession data (GPL v2). The game's own count, read from the
# profession window, overrides it at runtime (Known.lua).
import re, sys
s = open(sys.argv[1]).read()
a = s.index('PROFESSION_DATA.CLASSIC = {'); b = s.index('PROFESSION_DATA.BCC', a)
pat = re.compile(r'\[(\d+)\] = \{ (nil|\d+), (\d+), (\d+), (\d+), (\d+), \{ ([\d, ]*) \}, \{ ([\d, ]*) \}, (\d+) \}')
rows = sorted((int(m.group(1)), int(m.group(9))) for m in pat.finditer(s[a:b]) if int(m.group(9)) > 1 and int(m.group(1)) < 100000)
with open(sys.argv[2], 'w') as f:
    f.write('--[[ Data_NumMade.lua -- GENERATED by gen/make_nummade.py, do not edit.\n'
            'Recipes that make more than one item per cast. LibProfessionDB has no\n'
            '"number made" field; this comes from AtlasLootClassic (GPL v2). Opening the\n'
            'profession window replaces it with the game\'s own number. ]]\n'
            'ShuffleOptimizer.NumMade = {\n')
    for spell, n in rows: f.write(f'    [{spell}] = {n},\n')
    f.write('}\n')
print(len(rows))
